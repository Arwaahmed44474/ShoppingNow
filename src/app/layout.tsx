import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import '../Styles/globals.css'
import { Toaster } from 'sonner';
import Providers from "@/components/providers/Providers";
import Navbar from "@/components/layout/Navbar";
import Footer from "@/components/layout/Footer";
import { verifyToken } from "@/featuers/auth/server/auth.actions";
import { getCartItems } from "@/featuers/cart/servies/cartActions";
import { cartInitType } from "@/featuers/cart/slice/cartSlice";
import { getWishList } from "@/featuers/wishlist/servise/wishAction";
import { wishlistinitList } from "@/featuers/wishlist/slice/wishSlice";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {

  let authState = await verifyToken() // {isAuthentacted, userInfo}

  let CartRespose:cartInitType = {
      status: '',
      message: '',
      numOfCartItems: 0,
      cartId: null ,
      data: {
          products: [],
          totalCartPrice: 0
  }
  };

  let wishResponse:wishlistinitList = {
      status: '',
      count: 0,
      data: [],
  }


  if (authState.isAuthenticated) {


    let cartValues = await getCartItems();
    
    if (cartValues.status == 'success') {
      CartRespose = cartValues;
    }


    const wishResponseValues = await getWishList();
    if ('status' in wishResponseValues && wishResponseValues.status === 'success') {
      wishResponse = {
        status: wishResponseValues.status,
        count: wishResponseValues.count,
        data: wishResponseValues.data,
      };
    }

  }
  
 
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        
        <Providers preloadedAuth={{
          authReducer: authState,
          cartReducer: CartRespose,
          wishReducer: wishResponse
        }}>
          <Navbar/>
          {children} 
          <Footer/>
          <Toaster  position="top-right" richColors/>
        </Providers>
        
      </body>
      
    </html>
  );
}
